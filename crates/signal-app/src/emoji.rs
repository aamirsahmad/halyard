/// Emoji whose name matches every word of `query` (case-insensitive).
pub fn search(query: &str) -> Vec<&'static str> {
    let words: Vec<String> = query.split_whitespace().map(str::to_lowercase).collect();
    if words.is_empty() {
        return Vec::new();
    }
    CATEGORIES
        .iter()
        .flat_map(|c| c.emoji.iter())
        .filter(|(_, name)| {
            words
                .iter()
                .all(|w| name.split(' ').any(|n| n.starts_with(w.as_str())))
        })
        .map(|(e, _)| *e)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn search_by_name_prefix() {
        assert_eq!(search("thumbs up"), vec!["👍"]);
        assert!(search("heart").contains(&"❤️"));
        assert!(search("lau").contains(&"😂"));
        assert!(search("").is_empty());
        assert!(search("zzzznothing").is_empty());
    }

    #[test]
    fn quick_reactions_are_in_the_catalogue() {
        for r in crate::app::QUICK_REACTIONS {
            assert!(
                CATEGORIES
                    .iter()
                    .any(|c| c.emoji.iter().any(|(e, _)| *e == r)),
                "{r}"
            );
        }
    }

    #[test]
    fn no_duplicates() {
        let mut all: Vec<&str> = CATEGORIES
            .iter()
            .flat_map(|c| c.emoji.iter().map(|(e, _)| *e))
            .collect();
        let n = all.len();
        all.sort();
        all.dedup();
        assert_eq!(all.len(), n);
    }
}
